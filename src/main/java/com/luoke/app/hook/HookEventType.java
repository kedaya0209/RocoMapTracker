package com.luoke.app.hook;

/**
 * 钩子事件类型枚举
 * <p>
 * 定义了钩子系统中所有支持的事件类型。每个枚举值代表一种特定的事件，
 * 用于事件的分类和分发。钩子系统根据事件类型将事件分发给对应的钩子处理器。
 * <p>
 * 设计说明：
 * <ul>
 *   <li>使用枚举类型而非字符串或整数，提供编译期类型安全</li>
 *   <li>枚举值是单例的，比较时使用==而不是equals，性能更高</li>
 *   <li>枚举天然支持switch-case语句，便于事件分发逻辑编写</li>
 *   <li>枚举值可以作为Map的键，用于高效的钩子查找</li>
 * </ul>
 * <p>
 * 事件类型说明：
 * <ul>
 *   <li>PLAYER_UPDATE：玩家位置或状态更新事件</li>
 *   <li>MAP_CHANGED：地图配置或内容变化事件</li>
 *   <li>FRAME_CAPTURED：画面帧捕获完成事件</li>
 * </ul>
 * <p>
 * 性能优化要点：
 * <ul>
 *   <li>枚举比较是常量时间操作，性能极高</li>
 *   <li>枚举的ordinal()方法可用于数组索引，实现O(1)访问</li>
 *   <li>枚举值在类加载时初始化，没有运行时创建开销</li>
 * </ul>
 */
public enum HookEventType {

    /**
     * 玩家更新事件
     * <p>
     * 当玩家的位置、状态或其他属性发生变化时发布此事件。
     * 订阅此事件的钩子可以实时跟踪玩家状态变化，并做出相应的响应。
     * <p>
     * 使用场景：
     * <ul>
     *   <li>玩家位置更新：更新地图上的玩家标记位置</li>
     *   <li>玩家状态变化：根据玩家状态改变显示样式或触发特定逻辑</li>
     *   <li>数据同步：将玩家变化同步到其他模块或外部系统</li>
     * </ul>
     * <p>
     * 事件数据类型：
     * 通常为包含玩家位置、坐标、状态等信息的对象，具体类型由订阅者决定。
     * 例如：PlayerData、PlayerPosition或PlayerState对象。
     * <p>
     * 性能说明：
     * 玩家更新事件可能高频触发（如每秒多次），钩子处理器需要优化性能，
     * 避免复杂的计算或IO操作阻塞事件分发。
     */
    PLAYER_UPDATE,

    /**
     * 地图变化事件
     * <p>
     * 当地图配置、内容或显示模式发生变化时发布此事件。
     * 订阅此事件的钩子可以响应地图的变化，更新相关的UI或数据。
     * <p>
     * 使用场景：
     * <ul>
     *   <li>地图切换：加载新的地图文件，更新资源点和其他地图相关元素</li>
     *   <li>地图缩放：根据地图缩放级别调整显示元素的尺寸</li>
     *   <li>地图滚动：处理地图滚动后的视图更新</li>
     *   <li>图层管理：管理地图上的不同图层显示</li>
     * </ul>
     * <p>
     * 事件数据类型：
     * 通常为包含地图配置、尺寸、图层信息等的对象，具体类型由订阅者决定。
     * 例如：MapData、MapConfig或MapChangeInfo对象。
     * <p>
     * 性能说明：
     * 地图变化事件触发频率相对较低（如切换地图、大幅度缩放时），
     * 但可能涉及复杂的UI更新和资源加载，需要合理安排处理逻辑。
     */
    MAP_CHANGED,

    /**
     * 画面帧捕获事件
     * <p>
     * 当画面（通常指游戏画面或视频流）的一帧被成功捕获时发布此事件。
     * 订阅此事件的钩子可以对捕获的帧进行处理，如保存、分析或展示。
     * <p>
     * 使用场景：
     * <ul>
     *   <li>截图保存：将捕获的帧保存为图片文件</li>
     *   <li>图像分析：对捕获的帧进行OCR识别、目标检测等分析</li>
     *   <li>预览显示：将捕获的帧实时显示在UI预览窗口</li>
     *   <li>数据流处理：将捕获的帧传递给其他处理流水线</li>
     * </ul>
     * <p>
     * 事件数据类型：
     * 通常为包含图像数据的对象，可能是BufferedImage、Image或其他图像封装类型。
     * 在Native Image环境中，可能包含Native图像资源，需要谨慎管理生命周期。
     * <p>
     * Native资源管理说明：
     * <ul>
     *   <li>事件数据可能包含Native图像资源，需要正确释放以避免内存泄漏</li>
     *   <li>钩子处理器应该尽快处理或复制图像数据，避免持有Native资源过久</li>
   *   <li>在处理完成后应显式调用图像资源的释放方法（如dispose()）</li>
     * </ul>
     * <p>
     * 性能说明：
     * 画面帧捕获事件可能高频触发（如每秒30-60次），钩子处理器需要高效处理。
     * 建议：
     * <ul>
     *   <li>使用降采样或帧率控制减少处理频率</li>
     *   <li>将耗时操作（如保存图片）放到异步线程中执行</li>
     *   <li>避免在回调中创建大量临时对象，减少GC压力</li>
     * </ul>
     */
    FRAME_CAPTURED
}
