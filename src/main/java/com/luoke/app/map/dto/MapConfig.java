package com.luoke.app.map.dto;


import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import lombok.Data;

import java.util.List;

/**
 * 地图配置数据传输对象
 *
 * <p>该类封装了地图的所有核心配置信息，包括缩放级别、中心点坐标、边界范围、
 * 图层配置等。使用Lombok的@Data注解自动生成getter/setter方法，
 * 使用@JsonIgnoreProperties注解确保JSON反序列化时忽略未知字段，提高系统的健壮性。</p>
 *
 * <p>该类主要用于：
 * <ul>
 *   <li>定义地图视图的初始状态（缩放级别、中心点）</li>
 *   <li>限制地图的操作范围（最大/最小缩放级别、边界）</li>
 *   <li>配置图层的显示和交互（图层控制、图层列表）</li>
 *   <li>定义视觉资源（Logo、阴影、背景图）</li>
 *   <li>配置数据源路径和数据列表</li>
 * </ul></p>
 *
 * <p>在Native Image环境下，该类的字段设计考虑了内存效率和访问性能。
 * 所有字段都使用基本类型或轻量级对象，避免使用需要特殊处理的复杂类型。</p>
 *
 * @author RocoMapTracker
 * @version 1.0
 * @since 2024
 */
@Data
@JsonIgnoreProperties(ignoreUnknown = true)
public class MapConfig {
    /**
     * 地图的初始缩放级别
     *
     * <p>表示地图加载时的默认缩放层级。该值必须在minZoom和maxZoom之间。
     * 缩放级别决定了地图显示的详细程度，数值越大显示越详细。</p>
     *
     * <p>在Native Image环境下，使用int类型而非Integer类型可以避免包装类开销，
     * 减少内存占用并提高访问速度。</p>
     */
    private int zoom;

    /**
     * 地图的最大缩放级别
     *
     * <p>表示用户能够放大的最大层级。超过此级别的缩放将被限制。
     * 该值用于防止用户过度放大导致瓦片加载失败或性能问题。</p>
     *
     * <p>性能优化建议：设置为瓦片服务实际支持的最大级别，避免加载不存在的瓦片。</p>
     */
    private int maxZoom;

    /**
     * 地图的最小缩放级别
     *
     * <p>表示用户能够缩小的最小层级。低于此级别的缩放将被限制。
     * 该值用于防止用户过度缩小导致地图失去实际意义或显示错误。</p>
     *
     * <p>边界控制：配合maxBounds使用，确保用户始终在合理的地理范围内查看地图。</p>
     */
    private int minZoom;

    /**
     * 是否显示图层控制组件
     *
     * <p>控制地图右上角图层切换面板的显示状态。
     * true表示显示图层控制，允许用户切换不同图层；
     * false表示隐藏图层图层控制，用户无法手动切换图层。</p>
     *
     * <p>UI交互：该选项影响用户界面的复杂度，根据应用需求进行配置。</p>
     */
    private boolean layerControl;

    /**
     * 地图的初始中心点坐标
     *
     * <p>包含两个Double值的列表：[经度, 纬度]。
     * 表示地图加载时的默认中心位置。用户可以通过拖拽和缩放改变这个位置。</p>
     *
     * <p>坐标系统：使用WGS84坐标系（EPSG:4326），经度范围-180~180，纬度范围-90~90。</p>
     *
     * <p>内存管理：List<Double>在Native Image中需要特殊处理，确保序列化/反序列化正确。</p>
     */
    private List<Double> center;

    /**
     * 地图的最大边界范围
     *
     * <p>限制地图可拖拽范围的边界坐标。
     * 格式为：[[southWest经度, southWest纬度], [northEast经度, northEast纬度]]。
     * 用户无法将地图拖拽出此边界范围。</p>
     *
     * <p>边界锁定：这对于特定区域地图（如游戏地图、园区地图）尤为重要，
     * 确保用户始终关注目标区域。</p>
     *
     * <p>性能考虑：边界检测在每次拖拽时执行，保持边界计算简单高效。</p>
     */
    private List<List<Integer>> maxBounds;

    /**
     * 地图Logo的图片URL或路径
     *
     * <p>显示在地图上的品牌标识图片。可以是网络URL或本地文件路径。
     * Logo通常放置在地图的固定位置（如左下角），用于品牌展示。</p>
     *
     * <p>资源加载：在Native Image环境下，确保路径正确且资源可访问。
     * 网络URL需要处理跨域和加载超时问题。</p>
     */
    private String logo;

    /**
     * 地图标记点的阴影图片URL或路径
     *
     * <p>为地图上的标记点添加阴影效果，提升视觉深度感。
     * 阴影通常是半透明的PNG图片，放置在标记点下方。</p>
     *
     * <p>性能优化：阴影图片会影响渲染性能，大量标记点时考虑使用CSS阴影替代图片阴影。</p>
     *
     * <p>内存生命周期：阴影图片在地图卸载时释放，注意避免内存泄漏。</p>
     */
    private String pointShadow;

    /**
     * 地图背景图片URL或路径
     *
     * <p>在地图瓦片加载前或加载失败时显示的背景图片。
     * 也可以用作地图的基础底图，在其上叠加其他图层。</p>
     *
     * <p>视觉层次：背景图作为最底层，所有图层和标记都叠加在其上方。</p>
     *
     * <p>加载优化：背景图通常较大，建议使用压缩格式和适当的分辨率。</p>
     */
    private String mapBG;

    /**
     * 数据文件的前缀路径
     *
     * <p>所有地图数据文件的相对路径前缀。
     * 实际数据文件路径 = dataPrefix + dataList中的文件名。</p>
     *
     * <p>路径管理：使用前缀可以方便地切换数据源或迁移数据目录，
     * 而不需要修改所有数据文件路径。</p>
     *
     * <p>Native Image注意事项：确保前缀路径在打包后仍然有效，使用资源加载机制。</p>
     */
    private String dataPrefix;

    /**
     * 地图数据文件名列表
     *
     * <p>包含需要加载的地图数据文件的文件名列表。
     * 这些文件可能包含标记点、区域、路径等地图要素。</p>
     *
     * <p>加载顺序：列表中的文件按顺序加载，确保依赖关系的正确性。
     * 例如，先加载分类数据，再加载具体的标记点数据。</p>
     *
     * <p>内存管理：大量数据文件会占用较多内存，考虑分批加载或懒加载策略。</p>
     */
    private List<String> dataList;

    /**
     * 地图图层配置列表
     *
     * <p>定义地图上显示的各个图层及其配置信息。
     * 每个MapLayer代表一个独立的图层，如底图、POI图层、交通图层等。</p>
     *
     * <p>图层组织：图层按照列表顺序渲染，后面的图层覆盖前面的图层。
     * 图层可见性由layerControl控制，用户可以切换显示。</p>
     *
     * <p>性能优化：根据可见性和缩放级别控制图层的加载和渲染，避免不必要的资源消耗。</p>
     *
     * <p>Native资源管理：每个图层可能包含大量瓦片和标记，注意及时释放不可见图层的资源。</p>
     */
    private List<MapLayer> mapLayers;
}