package com.luoke.app.map.dto;

import lombok.Data;

/**
 * 地图图层配置数据传输对象
 *
 * <p>该类封装了单个地图图层的配置信息，包括图层选项、图层名称和显示索引。
 * 使用Lombok的@Data注解自动生成getter/setter方法，简化代码编写。</p>
 *
 * <p>该类主要用于：
 * <ul>
 *   <li>定义图层的基本属性（名称、选项）</li>
 *   <li>控制图层的显示顺序</li>
 *   <li>关联图层的瓦片源配置</li>
 * </ul></p>
 *
 * <p>在地图渲染过程中，图层按照index顺序进行绘制，index值较小的图层先绘制，
 * index值较大的图层后绘制（覆盖在上方）。这种设计允许精细控制地图的视觉层次。</p>
 *
 * <p>Native Image环境下的内存管理：
 * 图层对象在地图生命周期内一直存在，确保图层配置的稳定性。
 * LayerOption中的tileUrl字符串在Native Image中需要确保正确处理。</p>
 *
 * @author RocoMapTracker
 * @version 1.0
 * @since 2024
 */
@Data
public class MapLayer {
    /**
     * 图层的选项配置
     *
     * <p>封装了图层的核心配置信息，主要是瓦片服务的URL。
     * 通过LayerOption可以配置不同的瓦片源，实现多图层叠加效果。</p>
     *
     * <p>瓦片服务：瓦片URL通常支持{z}/{x}/{y}占位符，用于请求特定缩放级别和位置的瓦片图片。
     * 例如：https://tile.example.com/{z}/{x}/{y}.png</p>
     *
     * <p>资源生命周期：layerOption对象与MapLayer生命周期绑定，地图销毁时一起释放。
     * 在Native Image中，确保URL字符串的正确序列化。</p>
     *
     * <p>性能优化：瓦片URL的配置影响瓦片加载效率，选择高性能的瓦片服务CDN。</p>
     */
    private LayerOption layerOption;

    /**
     * 图层的显示名称
     *
     * <p>在图层控制面板中显示的用户友好名称。
     * 该名称用于标识图层，让用户能够理解图层的内容和用途。</p>
     *
     * <p>UI显示：名称会显示在图层切换组件中，支持中文显示。
     * 建议使用简短、明确的名称，如"底图"、"POI标记"、"交通路线"等。</p>
     *
     * <p>国际化考虑：如果需要支持多语言，可以将name改为资源引用key，
     * 在运行时根据语言环境解析实际显示文本。</p>
     *
     * <p>内存效率：字符串在Java中是不可变的，共享相同的名称字符串可以减少内存占用。</p>
     */
    private String name;

    /**
     * 图层的显示索引（层级）
     *
     * <p>控制图层的渲染顺序和叠加层次。Index值越小，图层越靠底层；
     * Index值越大，图层越靠顶层（会覆盖下方的图层）。</p>
     *
     * <p>渲染顺序：地图渲染器会按照index从小到大的顺序绘制各图层。
     * 例如：底图index=0，道路图层index=1，POI图层index=2。</p>
     *
     * <p>设计意图：使用int类型而非其他类型的原因：
     * <ul>
     *   <li>int类型在比较和排序时性能最优</li>
     *   <li>在Native Image中，int比Integer更节省内存</li>
     *   <li>支持负值，允许在现有图层前插入新图层</li>
     *   <li>数值直观，便于理解和调试</li>
     * </ul></p>
     *
     * <p>性能影响：图层的渲染顺序影响最终视觉效果，错误的index可能导致重要信息被遮挡。
     * 在配置文件中明确定义index，确保加载顺序的可预测性。</p>
     *
     * <p>扩展性：如果需要频繁调整图层顺序，可以考虑使用动态排序机制，
     * 但这会增加运行时开销。当前的静态index配置方式在性能上是最优的。</p>
     */
    private int index;
}