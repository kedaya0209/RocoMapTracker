package com.luoke.app.map.dto;

import lombok.Data;

/**
 * 地图标记点数据项传输对象
 *
 * <p>该类封装了地图上单个标记点的完整信息，包括位置、类型、标题、
 * 用户数据、时间戳等。使用Lombok的@Data注解自动生成getter/setter方法。</p>
 *
 * <p>该类主要用于：
 * <ul>
 *   <li>表示地图上的兴趣点（POI）、地标、用户标记等</li>
 *   <li>支持标记点的分类、搜索、筛选</li>
 *   <li>记录标记点的创建/更新时间</li>
 *   <li>关联标记点与图层的关系</li>
 * </ul></p>
 *
 * <p>在地图应用中，MapPointItem是用户交互的主要对象，
 * 用户可以点击查看详情、添加收藏、进行导航等操作。</p>
 *
 * <p>Native Image环境下的考虑：
 * <ul>
 *   <li>使用包装类（Integer、Long）而非基本类型，支持null值表示"未知"或"可选"</li>
 *   <li>Point对象引用确保坐标数据的结构化</li>
 *   <li>字符串字段使用String池优化内存</li>
 *   <li>整体设计轻量化，适合大量标记点场景</li>
 * </ul></p>
 *
 * <p>性能优化策略：
 * <ul>
 *   <li>对于大量标记点，考虑使用对象池减少GC压力</li>
 *   <li>字符串长度保持合理，避免过长的文本占用内存</li>
   *   <li>version字段支持增量更新，减少数据传输量</li>
 * </ul></p>
 *
 * @author RocoMapTracker
 * @version 1.0
 * @since 2024
 */
@Data
public class MapPointItem {
    /**
     * 标记点的类型标识
     *
     * <p>用于对标记点进行分类，不同类型的标记点可能显示不同的图标、
     * 具有不同的交互行为、属于不同的图层等。</p>
     *
     * <p>类型分类示例：
     * <ul>
     *   <li>1 - 普通标记点</li>
     *   <li>2 - 重要地标</li>
     *   <li>3 - 用户收藏点</li>
     *   <li>4 - 临时标记点</li>
     *   <li>10+ - 自定义类型</li>
     * </ul></p>
     *
     * <p>设计意图：
     * <ul>
     *   <li>使用Integer而非基本类型int，允许null表示"未分类"</li>
     *   <li>类型值与MapCategoryItem.markType关联，实现类型映射</li>
     *   <li>支持动态类型系统，便于扩展新的标记类型</li>
     *   <li>类型驱动UI渲染（图标、颜色、交互等）</li>
     * </ul></p>
     *
     * <p>性能考虑：
     * <ul>
     *   <li>类型判断使用switch比if-else更高效</li>
     *   <li>在Native Image中，类型检查可以被内联优化</li>
     *   <li>考虑使用枚举替代Integer，提高类型安全（但会增加内存）</li>
     * </ul></p>
     *
     * <p>内存管理：
     * <ul>
     *   <li>Integer是包装类，会占用额外内存（对象头+int值）</li>
     *   <li>对于大量标记点，可以考虑使用byte或short（如果类型数量有限）</li>
     *   <li>相同类型值可以共享Integer对象（Integer缓存）</li>
     * </ul></p>
     */
    private Integer markType;

    /**
     * 标记点的显示标题
     *
     * <p>标记点在地图上显示的名称或标题，通常是用户友好的简短文本。
     * 当用户点击标记点或鼠标悬停时，会显示此标题。</p>
     *
     * <p>UI显示：
     * <ul>
     *   <li>标题长度建议在20-50字符之间，确保可读性</li>
     *   <li>支持中文、英文等多种语言</li>
     *   <li>过长标题会在UI中被截断或换行</li>
     *   <li>null或空字符串表示"无标题"</li>
     * </ul></p>
     *
     * <p>设计意图：
     * <ul>
     *   <li>标题是标记点的标识，用户主要通过标题识别标记点</li>
     *   <li>支持null值，表示不显示标题（仅显示图标）</li>
     *   <li>字符串使用UTF-8编码，支持国际化</li>
     * </ul></p>
     *
     * <p>性能优化：
     * <ul>
     *   <li>字符串在Java中是不可变的，可以安全共享</li>
     *   <li>相同标题的标记点可以共享字符串对象</li>
     *   <li>避免过长的标题，增加内存和渲染负担</li>
     * </ul></p>
     *
     * <p>内存生命周期：
     * <ul>
     *   <li>标题字符串在MapPointItem生命周期内存在</li>
     *   <li>在Native Image中，常量字符串放入字符串常量池</li>
     *   <li>注意避免字符串拼接产生大量临时对象</li>
     * </ul></p>
     */
    private String title;

    /**
     * 标记点的唯一标识符
     *
     * <p>用于唯一标识地图上的一个标记点，确保在数据集中的唯一性。
     * 该ID用于标记点的增删改查、用户收藏、数据同步等操作。</p>
     *
     * <p>ID设计规范：
     * <ul>
     *   <li>必须是全局唯一的，不能重复</li>
     *   <li>格式建议：UUID或数据库自增ID的字符串表示</li>
     *   <li>长度适中（32-64字符），平衡唯一性和性能</li>
     *   <li>包含时间戳或序列号，便于排序和调试</li>
     * </ul></p>
     *
     * <p>使用场景：
     * <ul>
     *   <li>前端渲染时作为元素的key，确保DOM正确更新</li>
     *   <li>后端查询时的主键，快速定位标记点</li>
     *   <li>用户操作时的引用，如收藏、评论等</li>
     *   <li>数据同步时的唯一标识，避免重复</li>
     * </ul></p>
     *
     * <p>性能考虑：
     * <ul>
     *   <li>ID长度影响哈希计算性能，建议保持适中</li>
     *   <li>使用字符串ID便于序列化和跨系统传输</li>
     *   <li>在Native Image中，ID字符串可以被优化</li>
     * </ul></p>
     *
     * <p>安全考虑：
     * <ul>
     *   <li>避免使用可预测的ID（如连续数字），防止遍历攻击</li>
     *   <li>考虑使用UUIDv4或带随机因子的ID</li>
     *   <li>ID不包含敏感信息，可以暴露给前端</li>
     * </ul></p>
     */
    private String id;

    /**
     * 标记点的地理坐标位置
     *
     * <p>封装了标记点在地图上的精确位置信息，包括经度和纬度。
     * Point对象包含两个Double字段：lat（纬度）和lng（经度）。</p>
     *
     * <p>坐标系统：
     * <ul>
     *   <li>使用WGS84坐标系（EPSG:4326）</li>
     *   <li>经度（lng）范围：-180.0 到 180.0</li>
     *   <li>纬度（lat）范围：-90.0 到 90.0</li>
     *   <li>精度通常到小数点后6位（约0.1米精度）</li>
     * </ul></p>
     *
     * <p>设计意图：
     * <ul>
     *   <li>使用对象封装坐标，便于扩展（如增加高度、精度等）</li>
     *   <li>支持null值，表示"位置未知"或"待定"</li>
     *   <li>坐标是标记点的核心属性，不可为空（除非有特殊含义）</li>
     * </ul></p>
     *
     * <p>性能优化：
     * <ul>
     *   <li>坐标使用Double类型，保证足够的精度</li>
     *   <li>在Native Image中，对象分配可以被优化</li>
     *   <li>考虑使用两个基本类型字段替代Point对象，减少对象头开销</li>
     * </ul></p>
     *
     * <p>内存管理：
     * <ul>
     *   <li>Point对象在MapPointItem生命周期内存在</li>
     *   <li>大量标记点时，Point对象占用显著内存</li>
     *   <li>考虑使用坐标数组或紧凑格式存储大量坐标</li>
     * </ul></p>
     *
     * <p>Native资源管理：
     * <ul>
     *   <li>坐标数据在渲染时会被频繁访问</li>
     *   <li>确保坐标数据的内存布局优化缓存命中率</li>
     *   <li>避免在热路径中进行坐标转换操作</li>
     * </ul></p>
     */
    private Point point;

    /**
     * 用户的唯一标识符
     *
     * <p>标记标记点的创建者或关联用户的ID。用于用户标记、收藏、评论等
     * 需要与用户关联的功能。</p>
     *
     * <p>使用场景：
     * <ul>
     *   <li>标记点的创建者标识</li>
     *   <li>用户收藏点列表</li>
     *   <li>用户贡献的标记点统计</li>
     *   <li>权限控制（仅创建者可编辑）</li>
     * </ul></p>
     *
     * <p>设计意图：
     * <ul>
     *   <li>支持null值，表示"系统标记"或"匿名用户"</li>
     *   <li>与用户系统关联，实现个性化功能</li>
     *   <li>支持用户级别的标记点管理</li>
     * </ul></p>
     *
     * <p>安全考虑：
     * <ul>
     *   <li>uid不应暴露给其他用户，仅在服务端使用</li>
     *   <li>前端请求时需要身份验证</li>
     *   <li>防止伪造uid进行未授权操作</li>
     * </ul></p>
     *
     * <p>性能优化：
     * <ul>
     *   <li>uid通常不需要在前端渲染，可以序列化时忽略</li>
     *   <li>使用String类型便于与各种用户系统对接</li>
     * </ul></p>
     */
    private String uid;

    /**
     * 标记点所属的图层名称
     *
     * <p>标识标记点属于哪个地图图层。图层用于逻辑分组和显示控制，
     * 相同图层的标记点通常具有相似的性质或来源。</p>
     *
     * <p>图层作用：
     * <ul>
     *   <li>逻辑分组：按类型、来源、重要性等分组</li>
     *   <li>显示控制：批量显示/隐藏某类标记点</li>
     *   <li>渲染优化：按图层分批渲染，提高性能</li>
     *   <li>样式管理：同一图层的标记点共享样式</li>
     * </ul></p>
     *
     * <p>图层示例：
     * <pre>
     * "base" - 基础标记点
     * "poi" - 兴趣点
     * "user" - 用户标记
     * "traffic" - 交通设施
     * </pre></p>
     *
     * <p>设计意图：
     * <ul>
     *   <li>使用字符串而非对象引用，减少耦合</li>
     *   <li>支持null值，表示"未分类"或"默认图层"</li>
     *   <li>图层名称与MapLayer.name关联</li>
     * </ul></p>
     *
     * <p>性能考虑：
     * <ul>
     *   <li>图层筛选时使用字符串比较，可以考虑使用枚举或ID优化</li>
     *   <li>相同图层的标记点可以共享字符串对象</li>
     *   <li>在Native Image中，图层字符串可以被内联</li>
     * </ul></p>
     */
    private String layer;

    /**
     * 标记点的时间戳
     *
     * <p>记录标记点的创建时间或最后更新时间，使用Unix时间戳（毫秒级）。
     * 用于时间排序、增量更新、数据同步等功能。</p>
     *
     * <p>时间戳格式：
     * <ul>
     *   <li>Unix时间戳，自1970-01-01 00:00:00 UTC起的毫秒数</li>
     *   <li>示例：1704067200000 表示 2024-01-01 00:00:00 UTC</li>
     *   <li>使用Long类型，避免2038年问题</li>
     * </ul></p>
     *
     * <p>使用场景：
     * <ul>
     *   <li>数据同步：只同步时间戳之后变更的数据</li>
     *   <li>排序显示：按时间排序显示标记点</li>
     *   <li>统计分析：统计标记点的创建/更新趋势</li>
     *   <li>缓存控制：基于时间的缓存失效策略</li>
     * </ul></p>
     *
     * <p>设计意图：
     * <ul>
     *   <li>使用Long而非基本类型long，支持null表示"未知时间"</li>
     *   <li>毫秒级精度，满足大多数应用场景</li>
     *   <li>兼容Java的System.currentTimeMillis()</li>
     * </ul></p>
     *
     * <p>性能考虑：
     * <ul>
     *   <li>时间戳比较操作非常高效，适合排序</li>
     *   <li>在Native Image中，Long对象分配可以被优化</li>
     *   <li>对于大量标记点，考虑使用基本类型long</li>
     * </ul></p>
     *
     * <p>内存管理：
     * <ul>
     *   <li>Long是包装类，会占用额外内存</li>
     *   <li>如果时间精度要求不高，可以考虑秒级时间戳</li>
     *   <li>相同时间戳的标记点可以共享Long对象</li>
     * </ul></p>
     */
    private Long time;

    /**
     * 标记点的版本号
     *
     * <p>用于标记点的并发控制和增量更新。每次修改标记点时递增版本号，
     * 客户端可以通过版本号判断数据是否需要更新。</p>
     *
     * <p>版本号机制：
     * <ul>
     *   <li>初始版本：1 或 null（表示未版本化）</li>
     *   <li>更新规则：每次修改版本号+1</li>
   *   <li>单调递增：版本号只增不减</li>
     *   <li>版本比较：客户端本地版本 < 服务端版本时需要更新</li>
     * </ul></p>
     *
     * <p>使用场景：
     * <ul>
     *   <li>增量更新：只获取版本号变化的标记点</li>
     *   <li>冲突检测：基于版本号检测并发修改</li>
     *   <li>数据同步：客户端和服务端版本同步</li>
     *   <li>缓存失效：基于版本号失效缓存</li>
     * </ul></p>
     *
     * <p>设计意图：
     * <ul>
     *   <li>使用Integer而非基本类型int，支持null表示"无版本"</li>
     *   <li>乐观锁机制，避免悲观锁的性能开销</li>
     *   <li>支持分布式场景下的版本控制</li>
     * </ul></p>
     *
     * <p>性能考虑：
     * <ul>
     *   <li>版本号比较操作是O(1)，非常高效</li>
     *   <li>在Native Image中，Integer对象分配可以被优化</li>
     *   <li>对于高频更新场景，可以考虑使用long避免溢出</li>
     * </ul></p>
     *
     * <p>注意事项：
     * <ul>
     *   <li>版本号可能溢出（Integer.MAX_VALUE），需要处理</li>
     *   <li>版本号不是时间戳，不能用于时间排序</li>
     *   <li>版本号重置需要特殊处理（如升级时）</li>
     * </ul></p>
     */
    private Integer version;
}